export const customerRecordText = (
  c: {
    name?: string | null;
    source?: string | null;
    requirement?: string | null;
    interested?: string | null;
    stage?: string | null;
    lastAction?: string | null;
    notes?: string | null;
    rawConversation?: string | null;
  },
  productContext?: string | null
) => `【客户记录】
- 客户代号/称呼:${c.name || "(未填写)"}
- 来源:${c.source || "(未填写)"}
- 明确需求:${c.requirement || "(未填写)"}
- 感兴趣产品:${c.interested || "(未填写)"}
- 当前阶段:${c.stage || "(未填写)"}
- 上次动作:${c.lastAction || "(未填写)"}
- 沟通记录/备注:${c.notes || "(无)"}
${c.rawConversation ? `\n【真实聊天记录原文】\n${c.rawConversation}` : ""}
${productContext ? `\n【商家产品/服务背景(供话术参考,严禁编造超出此范围的能力与承诺)】\n${productContext}` : ""}`;
